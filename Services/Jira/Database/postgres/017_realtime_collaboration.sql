
CREATE TABLE IF NOT EXISTS issue_activity (
 event_id uuid PRIMARY KEY, tenant_id bigint NOT NULL, entity_type text NOT NULL, entity_id bigint NOT NULL,
 project_id bigint, actor_user_id bigint NOT NULL, action text NOT NULL, old_values text, new_values text, occurred_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_issue_activity_scope ON issue_activity(tenant_id,entity_type,entity_id,occurred_at);
CREATE TABLE IF NOT EXISTS issue_watchers (
 tenant_id bigint NOT NULL, issue_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY(tenant_id,issue_id,user_id)
);
CREATE TABLE IF NOT EXISTS project_workflow_rules (
 tenant_id bigint NOT NULL, project_id bigint NOT NULL, definition jsonb NOT NULL, PRIMARY KEY(tenant_id,project_id)
);
CREATE TABLE IF NOT EXISTS request_replays (
 tenant_id bigint NOT NULL, user_id bigint NOT NULL, key varchar(128) NOT NULL, hash text NOT NULL,
 status integer NOT NULL, response text NOT NULL, etag text, location text, issue_id bigint NOT NULL, created_at timestamptz NOT NULL,
 PRIMARY KEY(tenant_id,user_id,key)
);
CREATE TABLE IF NOT EXISTS boards (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL,
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 name varchar(200) NOT NULL, board_type varchar(30) NOT NULL DEFAULT 'KANBAN',
 filter_definition jsonb NOT NULL DEFAULT '{}', created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS board_columns (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, board_id bigint NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
 name varchar(150) NOT NULL, status_code varchar(50) NOT NULL, position integer NOT NULL,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(board_id,position), UNIQUE(board_id,status_code)
);
