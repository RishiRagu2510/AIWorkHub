CREATE TABLE IF NOT EXISTS project_allocations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, project_id bigint NOT NULL REFERENCES projects(id), user_id bigint NOT NULL CHECK(user_id>0),
 percentage integer NOT NULL CHECK(percentage BETWEEN 1 AND 100),
 start_date date NOT NULL, end_date date, CHECK(end_date IS NULL OR end_date>=start_date),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_allocations_user ON project_allocations(tenant_id,user_id,start_date);
