BEGIN;
CREATE TABLE IF NOT EXISTS employee_absence_policy (
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 year integer NOT NULL CHECK(year BETWEEN 2000 AND 2200),
 casual_days integer NOT NULL CHECK(casual_days BETWEEN 0 AND 366),
 sick_days integer NOT NULL CHECK(sick_days BETWEEN 0 AND 366),
 earned_days integer NOT NULL CHECK(earned_days BETWEEN 0 AND 366),
 holidays jsonb NOT NULL DEFAULT '[]',
 version integer NOT NULL DEFAULT 1,
 PRIMARY KEY(tenant_id,year)
);
CREATE TABLE IF NOT EXISTS employee_absence_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 employee_id bigint NOT NULL REFERENCES employees(id),
 kind varchar(20) NOT NULL CHECK(kind IN ('CASUAL','SICK','EARNED','UNPAID','WFH')),
 start_date date NOT NULL,
 end_date date NOT NULL CHECK(end_date>=start_date),
 days integer NOT NULL CHECK(days>0),
 reason varchar(1000) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
 decision_note varchar(1000),
 decided_by bigint REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 version integer NOT NULL DEFAULT 1,
 CHECK(EXTRACT(YEAR FROM start_date)=EXTRACT(YEAR FROM end_date))
);
CREATE INDEX IF NOT EXISTS ix_absence_employee_year ON employee_absence_requests(tenant_id,employee_id,start_date);
COMMIT;
