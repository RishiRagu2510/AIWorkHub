#!/usr/bin/env python3
"""Configure local IdentityTenant Google SMTP without passwords in shell history/output."""
import getpass
import json
import os
from pathlib import Path
import tempfile
import xml.etree.ElementTree as ET

project = Path(__file__).resolve().parents[2] / 'backend/services/IdentityTenant/IdentityTenant.Api/IdentityTenant.Api.csproj'
secret_id = ET.parse(project).findtext('.//UserSecretsId')
if not secret_id:
    raise SystemExit('IdentityTenant has no UserSecretsId.')

sender = input('Google Workspace sending email: ').strip()
if sender.count('@') != 1 or any(c.isspace() for c in sender):
    raise SystemExit('Enter a valid sending email address.')
password = getpass.getpass('Google app password (hidden; not your normal account password): ').replace(' ', '')
if len(password) != 16 or not password.isascii() or not password.isalnum():
    raise SystemExit('Expected the 16-character app password generated by Google.')

path = Path.home() / '.microsoft/usersecrets' / secret_id / 'secrets.json'
os.umask(0o077)
path.parent.mkdir(parents=True, exist_ok=True)
settings = json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else {}
settings.update({
    'Smtp:Host': 'smtp.gmail.com', 'Smtp:Port': '587', 'Smtp:EnableSsl': 'true',
    'Smtp:From': sender, 'Smtp:Username': sender, 'Smtp:Password': password,
})
settings.setdefault('Frontend:BaseUrl', 'http://localhost:5173')
fd, temporary = tempfile.mkstemp(dir=path.parent, prefix='.smtp-')
try:
    with os.fdopen(fd, 'w') as stream:
        json.dump(settings, stream, indent=2)
        stream.write('\n')
    os.replace(temporary, path)
finally:
    if os.path.exists(temporary):
        os.unlink(temporary)
print('Google SMTP saved in local .NET user secrets. No email was sent.')
print('Restart IdentityTenant to load the configuration.')
