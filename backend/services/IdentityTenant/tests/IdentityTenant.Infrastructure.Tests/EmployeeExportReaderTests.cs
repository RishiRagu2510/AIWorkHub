namespace IdentityTenant.Infrastructure.Tests;






public sealed class ExportDatabase : IAsyncLifetime
{
    private readonly PostgreSqlContainer postgres = new PostgreSqlBuilder("postgres:17").Build();
    public IdentityTenantDbContext Open() => new(new DbContextOptionsBuilder<IdentityTenantDbContext>().UseNpgsql(postgres.GetConnectionString()).Options);

    public async Task InitializeAsync()
    {
        await postgres.StartAsync();
        await using var db = Open();
        await db.Database.EnsureCreatedAsync();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS employee_career_history (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             tenant_id bigint NOT NULL REFERENCES tenants(id),
             employee_id bigint NOT NULL REFERENCES employees(id),
             effective_date date,
             recorded_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
             recorded_by bigint NOT NULL REFERENCES users(id),
             change_type varchar(30) NOT NULL,
             snapshot jsonb NOT NULL,
             note varchar(1000)
            )
            """);
    }

    public Task DisposeAsync() => postgres.DisposeAsync().AsTask();
}

public sealed class EmployeeExportReaderTests(ExportDatabase fixture) : IClassFixture<ExportDatabase>
{
    private static long Count;

    private sealed record Seeded(long TenantId, long AshaId, long BenId, long CyId);

    
    private async Task<Seeded> Seed(IdentityTenantDbContext db)
    {
        var n = Interlocked.Increment(ref Count);
        var tenantRow = new IdentityTenant.Domain.Entities.Tenant("Tenant " + n, "export-" + n);
        db.Tenants.Add(tenantRow);
        await db.SaveChangesAsync();
        var tenant = tenantRow.Id;
        var users = new[] { "asha", "ben", "cy" }.ToDictionary(x => x, x => new IdentityTenant.Domain.Entities.User(tenant, $"{x}{n}@x.test", x));
        db.Users.AddRange(users.Values);
        await db.SaveChangesAsync();
        long User(string name) => users[name].Id;

        var asha = new Employee { TenantId = tenant, UserId = User("asha"), EmployeeCode = "E1", FirstName = "Asha", LastName = "Kumar", WorkEmail = $"asha{n}@x.test", Phone = "98765", JoiningDate = new DateOnly(2024, 1, 15), EmploymentStatus = "ACTIVE" };
        var ben = new Employee { TenantId = tenant, UserId = User("ben"), EmployeeCode = "E2", FirstName = "Ben", LastName = "Rao", WorkEmail = $"ben{n}@x.test", JoiningDate = new DateOnly(2023, 5, 1), EmploymentStatus = "TERMINATED" };
        var cy = new Employee { TenantId = tenant, UserId = User("cy"), EmployeeCode = "E3", FirstName = "Cy", LastName = "Abel", WorkEmail = $"cy{n}@x.test", JoiningDate = new DateOnly(2022, 3, 1), EmploymentStatus = "ACTIVE" };
        db.Set<Employee>().AddRange(asha, ben, cy);
        await db.SaveChangesAsync();
        ben.IsDeleted = false;

        db.Set<EmployeeSkill>().AddRange(
            new EmployeeSkill { TenantId = tenant, EmployeeId = asha.Id, SkillName = "C#", Proficiency = 4, YearsOfExperience = 3.5m },
            new EmployeeSkill { TenantId = tenant, EmployeeId = asha.Id, SkillName = "SQL", Proficiency = 3, YearsOfExperience = 2m });
        db.Set<EmployeeExperience>().Add(new EmployeeExperience { TenantId = tenant, EmployeeId = asha.Id, Company = "Acme", Title = "Developer", StartDate = new DateOnly(2019, 1, 1), EndDate = new DateOnly(2021, 6, 30) });
        db.Set<EmployeeEducation>().Add(new EmployeeEducation { TenantId = tenant, EmployeeId = asha.Id, Institution = "Anna University", Qualification = "B.E.", FieldOfStudy = "CS", StartDate = new DateOnly(2015, 6, 1), EndDate = new DateOnly(2019, 5, 1) });
        db.Set<EmployeeCertification>().Add(new EmployeeCertification { TenantId = tenant, EmployeeId = asha.Id, Name = "AZ-900", Issuer = "Microsoft", IssuedDate = new DateOnly(2023, 2, 1), CredentialUrl = "https://secret.example/c" });
        db.Set<EmployeeLanguage>().Add(new EmployeeLanguage { TenantId = tenant, EmployeeId = asha.Id, Name = "English", Proficiency = "Native / Bilingual" });
        db.Set<EmployeeCompensation>().AddRange(
            new EmployeeCompensation { TenantId = tenant, EmployeeId = asha.Id, Ctc = 1000000, Bonus = 50000, Currency = "INR", EffectiveFrom = new DateOnly(2023, 1, 1), EffectiveTo = new DateOnly(2023, 12, 31) },
            new EmployeeCompensation { TenantId = tenant, EmployeeId = asha.Id, Ctc = 1200000, Bonus = 60000, Currency = "INR", EffectiveFrom = new DateOnly(2024, 1, 1) });
        await db.SaveChangesAsync();

        
        await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO employee_career_history(tenant_id,employee_id,effective_date,recorded_by,change_type,snapshot,note) VALUES({tenant},{cy.Id},{new DateOnly(2022, 3, 1)},{cy.UserId},{"BASELINE"},{"{\"designation\":\"Intern\",\"department\":\"Old\"}"}::jsonb,{(string?)null})");
        await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO employee_career_history(tenant_id,employee_id,effective_date,recorded_by,change_type,snapshot,note) VALUES({tenant},{cy.Id},{new DateOnly(2024, 3, 1)},{cy.UserId},{"CAREER_CHANGE"},{"{\"designation\":\"Engineer\",\"department\":\"Platform\",\"grade\":\"T2\",\"jobTitle\":\"Backend\"}"}::jsonb,{(string?)null})");

        return new Seeded(tenant, asha.Id, ben.Id, cy.Id);
    }

    private static JsonElement Json(EmployeeExport export) => JsonSerializer.SerializeToElement(export.Items, new JsonSerializerOptions(JsonSerializerDefaults.Web));

    [Fact]
    public async Task EveryPersonComesBackWithTheirSections_AndPay()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);

        var export = await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 500, CancellationToken.None);

        Assert.Equal(3, export.TotalCount);
        Assert.False(export.Truncated);
        var people = Json(export).EnumerateArray().ToList();
        Assert.Equal(["Abel", "Kumar", "Rao"], people.Select(p => p.GetProperty("lastName").GetString()!).ToArray());   

        var asha = people.Single(p => p.GetProperty("employeeCode").GetString() == "E1");
        Assert.Equal("98765", asha.GetProperty("phone").GetString());
        Assert.Equal(["C#", "SQL"], asha.GetProperty("skills").EnumerateArray().Select(s => s.GetProperty("skillName").GetString()!).ToArray());
        Assert.Equal(3.5m, asha.GetProperty("skills")[0].GetProperty("yearsOfExperience").GetDecimal());
        Assert.Equal("Acme", asha.GetProperty("experience")[0].GetProperty("company").GetString());
        Assert.Equal("2021-06-30", asha.GetProperty("experience")[0].GetProperty("endDate").GetString());
        Assert.Equal("Anna University", asha.GetProperty("education")[0].GetProperty("institution").GetString());
        Assert.Equal("AZ-900", asha.GetProperty("certifications")[0].GetProperty("name").GetString());
        Assert.Equal("Native / Bilingual", asha.GetProperty("languages")[0].GetProperty("proficiency").GetString());
        var pay = asha.GetProperty("compensation").EnumerateArray().ToList();
        Assert.Equal(2, pay.Count);
        Assert.Equal(1200000m, pay[1].GetProperty("ctc").GetDecimal());
        Assert.Equal(JsonValueKind.Null, pay[1].GetProperty("effectiveTo").ValueKind);
    }

    [Fact]
    public async Task APersonWithNothingRecorded_HasEmptyLists_NotMissingOnes()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);

        var ben = Json(await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 500, CancellationToken.None))
            .EnumerateArray().Single(p => p.GetProperty("employeeCode").GetString() == "E2");

        foreach (var section in new[] { "skills", "experience", "education", "certifications", "languages", "compensation" })
            Assert.Equal(0, ben.GetProperty(section).GetArrayLength());
        Assert.Equal(JsonValueKind.Null, ben.GetProperty("career").ValueKind);
    }

    [Fact]
    public async Task TheNewestCareerEntry_IsTheOneReturned()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);

        var cy = Json(await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 500, CancellationToken.None))
            .EnumerateArray().Single(p => p.GetProperty("employeeCode").GetString() == "E3");

        var career = cy.GetProperty("career");
        Assert.Equal("Engineer", career.GetProperty("designation").GetString());
        Assert.Equal("Platform", career.GetProperty("department").GetString());
        Assert.Equal("T2", career.GetProperty("grade").GetString());
    }

    [Fact]
    public async Task AStatusFilter_NarrowsThePeople_AndTheTotal()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);

        var export = await EmployeeExportReader.ReadAsync(db, seeded.TenantId, "ACTIVE", 500, CancellationToken.None);

        Assert.Equal(2, export.TotalCount);
        Assert.DoesNotContain(Json(export).EnumerateArray(), p => p.GetProperty("employeeCode").GetString() == "E2");
    }

    [Fact]
    public async Task ALimit_CutsTheListShort_AndSaysSo()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);

        var export = await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 2, CancellationToken.None);

        Assert.Equal(2, export.Items.Count);
        Assert.Equal(3, export.TotalCount);
        Assert.True(export.Truncated);
    }

    [Fact]
    public async Task OnlyTheAskedTenantsPeopleAreRead()
    {
        await using var db = fixture.Open();
        var first = await Seed(db);
        var second = await Seed(db);

        var export = await EmployeeExportReader.ReadAsync(db, first.TenantId, null, 500, CancellationToken.None);

        Assert.Equal(3, export.TotalCount);
        var ids = Json(export).EnumerateArray().Select(p => p.GetProperty("id").GetInt64()).ToHashSet();
        Assert.DoesNotContain(second.AshaId, ids);
        Assert.Contains(first.AshaId, ids);
    }

    [Fact]
    public async Task DeletedPeople_AreLeftOut()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);
        await db.Database.ExecuteSqlInterpolatedAsync($"UPDATE employees SET is_deleted=true WHERE id={seeded.BenId}");

        var export = await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 500, CancellationToken.None);

        Assert.Equal(2, export.TotalCount);
        Assert.DoesNotContain(Json(export).EnumerateArray(), p => p.GetProperty("employeeCode").GetString() == "E2");
    }

    [Fact]
    public async Task AddressesAndGovernmentIds_AreNeverPartOfIt()
    {
        await using var db = fixture.Open();
        var seeded = await Seed(db);
        await db.Database.ExecuteSqlInterpolatedAsync($"UPDATE employees SET aadhar_number='1234-5678-9999', permanent_address='1 Secret Road', emergency_contact_name='Hidden Person' WHERE id={seeded.AshaId}");

        var text = JsonSerializer.Serialize((await EmployeeExportReader.ReadAsync(db, seeded.TenantId, null, 500, CancellationToken.None)).Items, new JsonSerializerOptions(JsonSerializerDefaults.Web));

        Assert.DoesNotContain("1234-5678-9999", text);
        Assert.DoesNotContain("Secret Road", text);
        Assert.DoesNotContain("Hidden Person", text);
        Assert.DoesNotContain("secret.example", text);   
    }
}
